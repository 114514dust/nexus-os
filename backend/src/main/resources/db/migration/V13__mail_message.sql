-- 邮箱重要消息（Phase 16）
--
-- 只订阅「读」，不写邮箱：不标记已读、不移动、不删除服务端邮件，
-- 这样即使程序出问题，用户的邮箱也不会被改动。
--
-- 几个字段的取舍：
-- 1. (account, imap_uid) 唯一：IMAP 每次只能按 UID 判断「这封是不是收过了」。
--    用 message_id 不行 —— 有些邮件（尤其是营销系统发的）根本没有 Message-ID；
--    列名不叫 uid 是为了避开 H2 的 UID 函数名，减少方言差异。
-- 2. body 存纯文本全文（去 HTML 标签、截断到 2 万字）：LLM 判重要性和用户点开看详情
--    都需要正文，但没必要保留 HTML 结构与内联样式；
-- 3. important_level 与 important_score 都存：分数用于展示「为什么重要」，
--    等级用于筛选；两者都由判定链路写入，前端不重算，避免规则改动导致历史数据口径不一；
-- 4. todo_id 可空：高置信度邮件会自动建待办并回填，是「已处理」的凭据；
--    用户删掉待办后这里会悬挂，读取时按待办是否还存在兜底；
-- 5. read_flag 是抓取那一刻在邮箱里的已读状态，不是本系统里的已读。
CREATE TABLE mail_message (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account         VARCHAR(128) NOT NULL,
    imap_uid        BIGINT       NOT NULL,
    message_id      VARCHAR(255),
    sender_addr     VARCHAR(255) NOT NULL DEFAULT '',
    sender_name     VARCHAR(128),
    subject         VARCHAR(512) NOT NULL DEFAULT '',
    snippet         VARCHAR(1000),
    body            TEXT,
    sent_at         TIMESTAMP,
    received_at     TIMESTAMP    NOT NULL,
    important_score INT          NOT NULL DEFAULT 0,
    important_level VARCHAR(16)  NOT NULL DEFAULT 'low',
    score_reason    VARCHAR(512),
    verdict_by      VARCHAR(16)  NOT NULL DEFAULT 'rule',
    has_attachment  BOOLEAN      NOT NULL DEFAULT FALSE,
    read_flag       BOOLEAN      NOT NULL DEFAULT FALSE,
    todo_id         BIGINT,
    ignored         BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mail_message_account_uid UNIQUE (account, imap_uid)
);

CREATE INDEX idx_mail_message_received ON mail_message (received_at);
CREATE INDEX idx_mail_message_level ON mail_message (important_level);

