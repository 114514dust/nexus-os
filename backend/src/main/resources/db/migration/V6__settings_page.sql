-- 重建 layout 表：自增主键 + page_id 唯一外键（每个页面一条布局）
-- 先备份旧布局数据，迁移到默认页面（page_id=1）
CREATE TABLE layout_backup AS SELECT items_json, updated_at FROM layout;
DROP TABLE layout;
CREATE TABLE layout (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id    BIGINT      NOT NULL,
    items_json TEXT        NOT NULL,
    updated_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_layout_page UNIQUE (page_id)
);
INSERT INTO layout (page_id, items_json, updated_at)
    SELECT 1, items_json, updated_at FROM layout_backup;
DROP TABLE layout_backup;
