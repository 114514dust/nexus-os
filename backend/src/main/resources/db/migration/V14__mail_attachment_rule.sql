-- 邮箱增强（Phase 17）：附件、发件人规则
--
-- 一、mail_attachment
--   只存「元信息」，附件字节在用户第一次下载时才真正落到磁盘（stored_path 为空即未下载）。
--   理由：订阅一个 QQ 邮箱，光是营销邮件就有一堆几十兆的彩页 PDF，
--   收信时无脑落盘只会在几周内把磁盘填满，而其中 99% 不会被打开。
--   part_index 是 MIME 树里「第几个附件」的序号（从 0 开始），
--   同一封邮件的 MIME 结构不会变，所以下载时用同样的遍历顺序就能取回同一个附件。
--   size_bytes 取 JavaMail 的估算值，服务端不给时是 0（前端显示「大小未知」）。
CREATE TABLE mail_attachment (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_id       BIGINT       NOT NULL,
    part_index    INT          NOT NULL,
    filename      VARCHAR(255) NOT NULL,
    content_type  VARCHAR(128),
    size_bytes    BIGINT       NOT NULL DEFAULT 0,
    -- 本地绝对路径。为空表示还没下载过，仍可从 IMAP 现取
    stored_path   VARCHAR(512),
    downloaded_at TIMESTAMP,
    CONSTRAINT uk_mail_attachment_mail_part UNIQUE (mail_id, part_index)
);

CREATE INDEX idx_mail_attachment_mail ON mail_attachment (mail_id);

-- 二、mail_sender_rule
--   比 setting 里那行「永不重要的发件人」更强：能表达「这个人一律重要」，
--   也能表达「先算可关注、我自己决定要不要建待办」。
--   pattern 同时匹配发件地址与发件人显示名（学校就业中心常以中文名出现），
--   多个规则同时命中时取 pattern 更长的 —— 越具体越优先，这是人的直觉。
CREATE TABLE mail_sender_rule (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pattern     VARCHAR(128) NOT NULL,
    -- important 强制重要（≥70 自动建待办）/ watch 至少进「可关注」/ ignore 不提醒
    action      VARCHAR(16)  NOT NULL,
    note        VARCHAR(128),
    hit_count   INT          NOT NULL DEFAULT 0,
    last_hit_at TIMESTAMP,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mail_sender_rule_pattern UNIQUE (pattern)
);
