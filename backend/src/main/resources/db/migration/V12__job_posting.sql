-- 校招岗位池（Phase 15）
--
-- 与 job_application 的区别：那是「我已经投了的」，这是「外面正在招的」。
-- 两者的生命周期完全不同 —— 岗位会过期、会被下架、数量是几十上百条，
-- 混在一张表里会让求职追踪列表被大量没投的岗位淹没。
--
-- 几个字段的取舍：
-- 1. (source, source_id) 唯一：抓取每天都跑，靠站点自己的 id 去重，
--    而不是靠「公司+岗位名」这种会变的组合；
-- 2. 招聘公告通常是「一个公司一条、含多个岗位方向」，所以 title（公告标题）
--    和 positions（方向明细）分开存，加入追踪时再从中挑一个方向；
-- 3. job_id 可空：加入求职追踪后回填，是这条岗位「已处理」的凭据，
--    也避免用户重复添加同一家公司同一个岗位；
-- 4. published_at 用 DATE：站点只给到「10月30日」这一级，存时间戳是假精度。
CREATE TABLE job_posting (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        VARCHAR(32)   NOT NULL DEFAULT 'qiuzhaowang',
    source_id     VARCHAR(128)  NOT NULL,
    company       VARCHAR(128)  NOT NULL,
    title         VARCHAR(256)  NOT NULL DEFAULT '',
    positions     VARCHAR(2048),
    city          VARCHAR(256),
    cohort        VARCHAR(32),
    batch         VARCHAR(32),
    company_type  VARCHAR(32),
    category      VARCHAR(24)   NOT NULL DEFAULT 'autumn',
    detail_url    VARCHAR(512),
    announce_url  VARCHAR(1024),
    deadline_text VARCHAR(64),
    published_at  DATE,
    starred       BOOLEAN       NOT NULL DEFAULT FALSE,
    ignored       BOOLEAN       NOT NULL DEFAULT FALSE,
    job_id        BIGINT,
    fetched_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_job_posting_source UNIQUE (source, source_id)
);

CREATE INDEX idx_job_posting_published ON job_posting (published_at);
CREATE INDEX idx_job_posting_job ON job_posting (job_id);

