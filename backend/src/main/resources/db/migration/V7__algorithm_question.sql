CREATE TABLE algorithm_question (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(256) NOT NULL,
    difficulty   VARCHAR(16)  NOT NULL DEFAULT 'medium',  -- easy / medium / hard
    leetcode_url VARCHAR(512) NOT NULL,
    frequency    INT          NOT NULL DEFAULT 0,          -- 面试出现频率（热度），用于排序
    star         INT          NOT NULL DEFAULT 0,          -- 用户自评星级 0~5
    note         TEXT,                                     -- 解题思路 / 代码笔记
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

