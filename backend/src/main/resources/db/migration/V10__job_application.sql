-- 求职追踪（Phase 13）：投递记录 + 进度时间线
--
-- 说明：
-- 1. 岗位字段用 job_title 而不是 position —— position 在 SQL 里是保留函数名，
--    不加引号会解析失败，命名上避开更省事；
-- 2. next_at 用 DATE 而不是 TIMESTAMP：求职场景里用户只关心「哪天面试」，
--    精确到时分反而增加录入负担，具体时间写在 next_action 里即可；
-- 3. 时间线单独建表 job_event，而不是在 job_application 上盖一个 stage 字段了事：
--    只有留下每次变更的时间点，才可能回答「投递后多久收到笔试」这类问题。
CREATE TABLE job_application (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company     VARCHAR(128) NOT NULL,
    job_title   VARCHAR(128) NOT NULL DEFAULT '',
    category    VARCHAR(24)  NOT NULL DEFAULT 'autumn',
    stage       VARCHAR(24)  NOT NULL DEFAULT 'applied',
    url         VARCHAR(1024),
    next_action VARCHAR(256),
    next_at     DATE,
    starred     BOOLEAN      NOT NULL DEFAULT FALSE,
    note        TEXT,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_job_application_stage ON job_application (stage);
CREATE INDEX idx_job_application_next_at ON job_application (next_at);

CREATE TABLE job_event (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      BIGINT      NOT NULL,
    stage       VARCHAR(24) NOT NULL,
    note        VARCHAR(512),
    occurred_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_job_event_job FOREIGN KEY (job_id)
        REFERENCES job_application (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_event_job ON job_event (job_id);

